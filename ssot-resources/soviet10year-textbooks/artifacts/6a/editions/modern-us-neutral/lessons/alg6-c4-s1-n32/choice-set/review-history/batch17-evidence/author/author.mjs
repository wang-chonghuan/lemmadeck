function add(number, id, mode, stem, rows, task, unit, limitations = [], concepts = [4], figures = []) {
  const alphabet = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ';
  rows = (placements[id] || rows.map((_,i)=>i)).map(i=>rows[i]);
  questions.push({
    id, source_numbers: [number],
    view: { mode, stem, figure_ids: figures, options: rows.map((r,i)=>({ id:alphabet[i],text:r.text,figure_ids:[] })) },
    intent: {
      task, source_solution: source.sources.find(s=>s.source_number===number).independent_solution,
      unit_reason: unit, concept_blocks: concepts, limitations,
      figure_observations: figures.map(figure_id=>({ figure_id, observation:source.figure_observations.find(f=>f.figure_id===figure_id).observation })),
    },
    key: {
      correct: rows.flatMap((r,i)=>r.truth==='correct'?[alphabet[i]]:[]),
      rationales: rows.map((r,i)=>({ option_id:alphabet[i],truth:r.truth,derivation:r.derivation,misconception:r.misconception })),
    },
  });
}
