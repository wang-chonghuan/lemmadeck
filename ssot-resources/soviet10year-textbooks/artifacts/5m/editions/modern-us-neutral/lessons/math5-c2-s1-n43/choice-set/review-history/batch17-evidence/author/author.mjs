const yes = (text, derivation) => ({ text, truth: 'correct', derivation, misconception: null });
const no = (text, procedure) => ({ text, truth: 'incorrect', derivation: procedure, misconception: procedure });
function add(number, id, mode, stem, rows, task, unit, limitations = []) {
  questions.push({
    id, source_numbers: [number],
    view: { mode, stem, figure_ids: [], options: rows.map((r,i)=>({ id: 'ABCD'[i], text:r.text, figure_ids:[] })) },
    intent: {
      task, source_solution: source.sources.find(s=>s.source_number===number).independent_solution,
      unit_reason: unit, concept_blocks: [], limitations, figure_observations: [],
    },
    key: {
      correct: rows.flatMap((r,i)=>r.truth==='correct'?['ABCD'[i]]:[]),
      rationales: rows.map((r,i)=>({ option_id:'ABCD'[i], truth:r.truth, derivation:r.derivation, misconception:r.misconception })),
    },
  });
}
