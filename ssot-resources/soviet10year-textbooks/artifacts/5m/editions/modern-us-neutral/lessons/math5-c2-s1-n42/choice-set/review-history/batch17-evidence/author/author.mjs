import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const source = JSON.parse(fs.readFileSync(path.join(root, 'source-solutions.json'), 'utf8'));
if (!source.stage_complete) throw new Error('Source phase incomplete');
if (fs.existsSync(path.join(root, 'draft.json'))) throw new Error('Do not overwrite a snapshot');
const questions = [];
const correct = (text, derivation) => ({ text, truth: 'correct', derivation, misconception: null });
const wrong = (text, procedure) => ({ text, truth: 'incorrect', derivation: procedure, misconception: procedure });
function add(number, id, mode, stem, rows, task, unit, limitations = []) {
  const solution = source.sources.find(s => s.source_number === number).independent_solution;
  const options = rows.map((row, i) => ({ id: 'ABCD'[i], text: row.text, figure_ids: [] }));
  questions.push({
    id, source_numbers: [number], view: { mode, stem, figure_ids: [], options },
    intent: {
      task, source_solution: solution, unit_reason: unit,
      concept_blocks: ['756','757','758','759','760','761','762','763','770'].includes(number) ? [7] : [],
      limitations, figure_observations: [],
    },
    key: {
      correct: rows.flatMap((row, i) => row.truth === 'correct' ? ['ABCD'[i]] : []),
      rationales: rows.map((row, i) => ({ option_id: 'ABCD'[i], truth: row.truth, derivation: row.derivation, misconception: row.misconception })),
    },
  });
}
